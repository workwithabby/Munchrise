-- ---------------------------------------------------------------------
-- Profiles (one per auth user)
-- ---------------------------------------------------------------------
create table public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  email       text,
  first_name  text not null default '',
  last_name   text not null default '',
  name        text not null default '',
  phone       text,
  avatar      text,
  role        text not null default 'user' check (role in ('user', 'admin', 'rider')),
  created_at  timestamptz not null default now()
);

-- Role helpers (security definer so policies can use them without recursion)
create function public.my_role() returns text
  language sql stable security definer set search_path = public as
$$ select role from public.profiles where id = auth.uid() $$;

create function public.is_admin() returns boolean
  language sql stable security definer set search_path = public as
$$ select coalesce(public.my_role() = 'admin', false) $$;

-- A new auth user always becomes a customer, whatever the metadata says.
create function public.handle_new_user() returns trigger
  language plpgsql security definer set search_path = public as
$$
declare
  v_first text := coalesce(new.raw_user_meta_data ->> 'first_name', '');
  v_last  text := coalesce(new.raw_user_meta_data ->> 'last_name', '');
begin
  insert into public.profiles (id, email, first_name, last_name, name, role)
  values (
    new.id,
    new.email,
    v_first,
    v_last,
    coalesce(nullif(btrim(v_first || ' ' || v_last), ''), new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)),
    'user'
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

