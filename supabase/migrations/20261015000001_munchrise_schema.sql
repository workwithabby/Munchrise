-- Munchrise: database schema, security rules and server-side functions
-- Run once (Supabase Dashboard > SQL Editor > paste > Run), or with
-- `supabase db push`. Safe to read top to bottom.
--
-- Roles: 'user' (customer), 'admin', 'rider'. A visitor without an account
-- is a guest and can only read the menu. Roles are NEVER set from the app:
-- sign-up always creates a 'user'; promote someone with the SQL at the bottom.
