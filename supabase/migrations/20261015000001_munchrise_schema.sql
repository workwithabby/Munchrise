-- Points balance for the signed-in user
create function public.my_points() returns integer
  language sql stable security definer set search_path = public as
$$ select coalesce(sum(points), 0)::integer from public.reward_ledger where user_id = auth.uid() $$;

-- Place an order from the signed-in user's cart.
-- p_shipping: {"fullName","phone","address","city","notes"}
create function public.place_order(
  p_shipping    jsonb,
  p_payment     text,
  p_promo       text    default null,
  p_use_voucher boolean default false
) returns public.orders
  language plpgsql security definer set search_path = public as
$$
declare
  v_uid            uuid := auth.uid();
  v_line           record;
  v_subtotal       numeric := 0;
  v_promo          public.promo_codes%rowtype;
  v_promo_discount numeric := 0;
  v_voucher_total  numeric := 0;
  v_reward         numeric := 0;
  v_remaining      numeric;
  v_voucher        record;
  v_fee            numeric;
  v_discount       numeric;
  v_total          numeric;
  v_points         integer;
  v_id             text;
  v_order          public.orders;
  v_code           text := upper(btrim(coalesce(p_promo, '')));
begin
  if v_uid is null then raise exception 'Please sign in first.'; end if;
  if public.my_role() <> 'user' then raise exception 'Only customers can place orders.'; end if;
  if p_payment not in ('GCash', 'Credit/Debit Card', 'Cash on Delivery') then
    raise exception 'Choose a valid payment method.';
  end if;
  if length(btrim(coalesce(p_shipping ->> 'fullName', ''))) < 2
     or length(btrim(coalesce(p_shipping ->> 'phone', ''))) < 7
     or length(btrim(coalesce(p_shipping ->> 'address', ''))) < 5
     or length(btrim(coalesce(p_shipping ->> 'city', ''))) < 2 then
    raise exception 'Please complete your delivery details.';
  end if;

  -- price the cart with the REAL prices and check stock (rows locked)
  for v_line in
    select c.product_id, c.quantity, p.name, p.price, p.stock
    from public.cart_items c
    join public.products p on p.id = c.product_id
    where c.user_id = v_uid
    order by p.id
    for update of p
  loop
    if v_line.quantity > v_line.stock then
      raise exception '% only has % left in stock.', v_line.name, v_line.stock;
    end if;
    v_subtotal := v_subtotal + v_line.price * v_line.quantity;
  end loop;

  if v_subtotal = 0 then raise exception 'Your cart is empty.'; end if;

  -- promo code
  if v_code <> '' then
    select * into v_promo from public.promo_codes where code = v_code and active;
    if found and (v_promo.min_subtotal is null or v_subtotal >= v_promo.min_subtotal) then
      v_promo_discount := case
        when v_promo.type = 'percent' then round(v_subtotal * v_promo.value / 100)
        else least(v_promo.value, v_subtotal)
      end;
    else
      v_code := '';
    end if;
  end if;

  -- reward vouchers (oldest first, whole vouchers)
  if p_use_voucher then
    select coalesce(sum(discount), 0) into v_voucher_total
      from public.vouchers where user_id = v_uid and used_at is null;
    v_reward := greatest(0, least(v_voucher_total, v_subtotal - v_promo_discount));
  end if;

  v_discount := v_promo_discount + v_reward;
  v_fee      := case when v_subtotal >= 500 then 0 else 49 end;
  v_total    := greatest(0, v_subtotal - v_discount + v_fee);
  v_points   := floor(v_total / 10)::integer;
  v_id       := 'MR-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));

  insert into public.orders
    (id, user_id, subtotal, delivery_fee, discount, total, promo_code, payment, shipping, points_earned)
  values
    (v_id, v_uid, v_subtotal, v_fee, v_discount, v_total,
     nullif(v_code, ''), p_payment, p_shipping, v_points)
  returning * into v_order;

  insert into public.order_items (order_id, product_id, name, price, quantity)
  select v_id, c.product_id, p.name, p.price, c.quantity
  from public.cart_items c join public.products p on p.id = c.product_id
  where c.user_id = v_uid;

  update public.products p
     set stock = p.stock - c.quantity
    from public.cart_items c
   where c.user_id = v_uid and c.product_id = p.id;

  insert into public.order_status_history (order_id, status) values (v_id, 'Placed');

  -- use up vouchers
  if v_reward > 0 then
    v_remaining := v_reward;
    for v_voucher in
      select id, discount from public.vouchers
      where user_id = v_uid and used_at is null order by created_at
    loop
      exit when v_remaining <= 0;
      update public.vouchers set used_at = now() where id = v_voucher.id;
      v_remaining := v_remaining - v_voucher.discount;
    end loop;
  end if;

  if v_points > 0 then
    insert into public.reward_ledger (user_id, points, kind, label)
    values (v_uid, v_points, 'earn', 'Order ' || v_id);
  end if;

  insert into public.notifications (user_id, title, message, type)
  values (v_uid, 'Order placed',
          'Your order ' || v_id || ' is now Placed. +' || v_points || ' points!', 'order');

  delete from public.cart_items where user_id = v_uid;

  return v_order;
end;
$$;

-- Admin: any status. Rider: take an order that is Preparing (must be online),
-- then mark only their own order Delivered. Customers are notified.
create function public.set_order_status(p_order text, p_status text)
  returns public.orders
  language plpgsql security definer set search_path = public as
$$
declare
  v_uid   uuid := auth.uid();
  v_role  text := public.my_role();
  v_order public.orders;
  v_name  text;
begin
  if v_uid is null then raise exception 'Please sign in first.'; end if;
  if p_status not in ('Placed', 'Preparing', 'Out for Delivery', 'Delivered') then
    raise exception 'Unknown status.';
  end if;

  select * into v_order from public.orders where id = p_order for update;
  if not found then raise exception 'Order not found.'; end if;
  if v_order.status = p_status then return v_order; end if;

  select name into v_name from public.profiles where id = v_uid;

  if v_role = 'admin' then
    update public.orders set status = p_status where id = p_order returning * into v_order;
  elsif v_role = 'rider' then
    if p_status = 'Out for Delivery' and v_order.status = 'Preparing' then
      if not coalesce((select online from public.rider_settings where user_id = v_uid), true) then
        raise exception 'You are offline. Go online to take orders.';
      end if;
      update public.orders set status = p_status, rider_id = v_uid, rider_name = v_name
       where id = p_order returning * into v_order;
    elsif p_status = 'Delivered' and v_order.status = 'Out for Delivery' and v_order.rider_id = v_uid then
      update public.orders set status = p_status where id = p_order returning * into v_order;
    else
      raise exception 'You cannot make that change to this order.';
    end if;
  else
    raise exception 'Not allowed.';
  end if;

  insert into public.order_status_history (order_id, status) values (p_order, p_status);

  insert into public.notifications (user_id, title, message, type)
  values (
    v_order.user_id,
    'Order ' || p_status,
    case
      when v_order.rider_name is not null and p_status = 'Out for Delivery'
        then 'Your order ' || v_order.id || ' is out for delivery with ' || v_order.rider_name || '.'
      else 'Your order ' || v_order.id || ' is now ' || lower(p_status) || '.'
    end,
    'order'
  );

  return v_order;
end;
$$;

-- Swap points for a voucher: 100 -> P50, 180 -> P100, 250 -> P150
create function public.redeem_reward(p_points integer) returns numeric
  language plpgsql security definer set search_path = public as
$$
declare
  v_uid      uuid := auth.uid();
  v_discount numeric;
begin
  if v_uid is null then raise exception 'Please sign in first.'; end if;
  v_discount := case p_points when 100 then 50 when 180 then 100 when 250 then 150 else null end;
  if v_discount is null then raise exception 'Unknown reward.'; end if;
  if public.my_points() < p_points then
    raise exception 'You need % points for this reward.', p_points;
  end if;

  insert into public.reward_ledger (user_id, points, kind, label)
  values (v_uid, -p_points, 'redeem', 'Redeemed P' || v_discount || ' voucher');
  insert into public.vouchers (user_id, discount) values (v_uid, v_discount);
  return v_discount;
end;
$$;

